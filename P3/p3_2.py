def objetivo_reactor(x):
    x1, x2, x3, x4, x5, x6, x7, x8 = x
    return 0.4 * (x1 / x7) ** 0.67 + 0.4 * (x2 / x8) ** 0.67 + 10.0 - x1 - x2

def restricciones_reactor(x):
    x1, x2, x3, x4, x5, x6, x7, x8 = x
    g1 = 0.0588 * x5 * x7 + 0.1 * x1 - 1.0
    g2 = 0.0588 * x6 * x8 + 0.1 * x1 + 0.1 * x2 - 1.0
    g3 = (4.0 * x3 / x5 + 2.0 / (x3 ** 0.71 * x5) + 0.0588 * x7 / (x3 ** 1.3) - 1.0)
    g4 = (4.0 * x4 / x6 + 2.0 / (x4 ** 0.71 * x6) + 0.0588 * x8 / (x4 ** 1.3) - 1.0)
    return np.array([g1, g2, g3, g4])

