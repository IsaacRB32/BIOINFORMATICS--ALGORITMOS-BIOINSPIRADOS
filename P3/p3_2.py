def resumen_estadistico(valores):
    valores = np.array(valores, dtype=float)
    return {
        "mejor": np.min(valores),
        "peor": np.max(valores),
        "promedio": np.mean(valores),
        "mediana": np.median(valores),
        "desviacion_estandar": np.std(valores, ddof=1)
    }

def wilcoxon_seguro(vals_g, vals_l):
    vals_g = np.asarray(vals_g, dtype=float)
    vals_l = np.asarray(vals_l, dtype=float)
    dif = vals_g - vals_l
    if np.allclose(dif, 0.0):
        return np.nan, 1.0
    no_cero = dif[~np.isclose(dif, 0.0)]
    if no_cero.size < 1:
        return np.nan, 1.0
    try:
        return wilcoxon(vals_g, vals_l, zero_method='wilcox')
    except ValueError:
        return np.nan, 1.0

def ejecutar_experimento(funcion_objetivo, funcion_restricciones,
                         limites_inferiores, limites_superiores):
    resultados_global, resultados_local = [], []
    for ejecucion in range(1, NUM_EJECUCIONES + 1):
        semilla = ejecucion
        res_g = pso_global(funcion_objetivo, funcion_restricciones,
                           limites_inferiores, limites_superiores, semilla=semilla)
        res_l = pso_local_double_linked(funcion_objetivo, funcion_restricciones,
                                        limites_inferiores, limites_superiores, semilla=semilla)
        resultados_global.append(res_g)
        resultados_local.append(res_l)

    def extraer_datos(res_list):
        return {
            "aptitud":  np.array([r["mejor_aptitud"] for r in res_list]),
            "svr":      np.array([r["mejor_svr"] for r in res_list]),
            "dp_final": np.array([r["historial_dp"][-1] for r in res_list]),
            "dv_final": np.array([r["historial_dv"][-1] for r in res_list]),
            "dc_final": np.array([r["historial_dc"][-1] for r in res_list]),
            "dp_mean":  np.array([np.mean(r["historial_dp"]) for r in res_list]),
            "dv_mean":  np.array([np.mean(r["historial_dv"]) for r in res_list]),
            "dc_mean":  np.array([np.mean(r["historial_dc"]) for r in res_list]),
            "hist_dp":  np.array([r["historial_dp"] for r in res_list]),
            "hist_dv":  np.array([r["historial_dv"] for r in res_list]),
            "hist_dc":  np.array([r["historial_dc"] for r in res_list]),
            "hist_apt": np.array([r["historial_aptitud"] for r in res_list]),
            "hist_svr": np.array([r["historial_svr"] for r in res_list]),
        }

    return {"global": extraer_datos(resultados_global),
            "local":  extraer_datos(resultados_local)}

