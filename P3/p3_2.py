def construir_tabla_y_wilcoxon(datos):
    metricas = [
        ('aptitud',  'Aptitud f(x)'),
        ('svr',      'SVR (Violación de Restricciones)'),
        ('dp_final', 'Dp (Posición Final)'),
        ('dv_final', 'Dv (Velocidad Final)'),
        ('dc_final', 'Dc (Cognitiva Final)'),
        ('dp_mean',  'Dp (Posición Promedio)'),
        ('dv_mean',  'Dv (Velocidad Promedio)'),
        ('dc_mean',  'Dc (Cognitiva Promedio)')
    ]
    filas, wilcoxon_res = [], []
    for key, label in metricas:
        vals_g = datos["global"][key]
        vals_l = datos["local"][key]
        st_g = resumen_estadistico(vals_g)
        st_l = resumen_estadistico(vals_l)
        filas.append({"Algoritmo": "PSO Global",   "Métrica": label, **st_g})
        filas.append({"Algoritmo": "PSO Local DL", "Métrica": label, **st_l})
        w_stat, p_val = wilcoxon_seguro(vals_g, vals_l)
        wilcoxon_res.append({
            "Métrica": label,
            "Estadístico W": w_stat,
            "p-valor": p_val,
            "Significativo (p < 0.05)": "Sí" if (not np.isnan(p_val) and p_val < 0.05) else "No"
        })
    return pd.DataFrame(filas), pd.DataFrame(wilcoxon_res)

